#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Build the taxonomy-change crosswalk used by the daily literature run.

The source of truth is ``_data/name_issues.json`` (generated by
``.github/workflows/build_name_issues.py``).  This script only reorganizes the
eight species-level synonym/combination pairs into a small, readable table plus
a machine-readable JSON file; it does not decide taxonomy and it does not edit
the site's species names.

Usage::

    python _tools/build_taxonomy_crosswalk.py
    python _tools/build_taxonomy_crosswalk.py --check

Outputs:
    _data/taxonomy_crosswalk.json
    _reports/library-reading/taxonomy-crosswalk.md
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NAME_ISSUES_PATH = ROOT / "_data" / "name_issues.json"
OUT_JSON = ROOT / "_data" / "taxonomy_crosswalk.json"
OUT_MD = ROOT / "_reports" / "library-reading" / "taxonomy-crosswalk.md"


def load_json(path: Path):
    with path.open("r", encoding="utf-8") as fh:
        return json.load(fh)


def dump_json(path: Path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as fh:
        json.dump(data, fh, ensure_ascii=False, indent=1)
        fh.write("\n")


def source_links(links, sources):
    """Return markdown links for authority sources in a stable order."""
    by_source = {item.get("source"): item.get("url") for item in (links or [])}
    parts = []
    for source in sources or sorted(by_source):
        url = by_source.get(source)
        if url:
            parts.append("[%s](%s)" % (source.upper(), url))
        else:
            parts.append(source.upper())
    return " / ".join(parts) if parts else "—"


def stable_sources(pair):
    order = ["gbif", "col", "bsf"]
    present = set(pair.get("sources") or [])
    return [source for source in order if source in present] + sorted(present - set(order))


def guidance(pair):
    site = pair.get("our") or {}
    authority = pair.get("external") or {}
    site_latin = site.get("latin") or ""
    authority_name = authority.get("name") or authority.get("latin") or ""
    relation = pair.get("relation") or ""
    direction = pair.get("direction") or ""
    disputed = bool(pair.get("disputed"))
    genus_from = (authority.get("latin") or "").split()[0] if authority.get("latin") else ""
    genus_to = site_latin.split()[0] if site_latin else ""

    if relation == "synonym" and direction == "external":
        return (
            "本站两页并存：写 %s 时注明 %s 将其列为 %s 的异名；"
            "写 %s 时反向注明。不要删页或改学名，除非用户确认。"
            % (site_latin, "、".join(source.upper() for source in stable_sources(pair)),
               authority.get("latin") or authority_name, authority.get("latin") or authority_name)
        )
    if disputed and direction == "disputed":
        return "关系未定：保留双名并标「待核」，不要写成单方结论。"
    if direction == "site":
        suffix = "；该组合仍有争议，不要写成学界共识" if disputed else ""
        return (
            "本站现用 %s；旧文献用 %s 时写「当时置于 %s，本站现置于 %s」%s。"
            % (site_latin, authority_name, genus_from or "旧属", genus_to or "现属", suffix)
        )
    return "按原文保留旧名，并注明与本站现用名的关系；不确定时标「待核」。"


def status(pair):
    if pair.get("recordable"):
        return "可记录（待处理）"
    if pair.get("disputed"):
        return "争议／未定"
    return "待核"


def build_entry(pair):
    site = dict(pair.get("our") or {})
    authority = dict(pair.get("external") or {})
    receiving = pair.get("receiving") or {}
    site_latin = site.get("latin") or ""
    authority_latin = authority.get("latin") or ""
    return {
        "site": {
            "latin": site_latin,
            "zh": site.get("zh") or "",
            "slug": site.get("slug") or "",
            "url": "/species/%s/" % site.get("slug") if site.get("slug") else "",
            "family_zh": site.get("family_zh") or "",
            "family_latin": site.get("family_latin") or "",
        },
        "authority": {
            "name": authority.get("name") or "",
            "latin": authority_latin,
            "links": pair.get("external_links") or [],
        },
        "receiving": {
            "latin": receiving.get("latin") or "",
            "zh": receiving.get("zh") or "",
            "slug": receiving.get("slug") or "",
            "url": "/species/%s/" % receiving.get("slug") if receiving.get("slug") else "",
            "in_site": bool(receiving.get("in_site")),
        },
        "relation": pair.get("relation") or "",
        "direction": pair.get("direction") or "",
        "disputed": bool(pair.get("disputed")),
        "sources": stable_sources(pair),
        "genus_from": authority_latin.split()[0] if authority_latin else "",
        "genus_to": site_latin.split()[0] if site_latin else "",
        "guidance": guidance(pair),
        "status": status(pair),
        "recordable": bool(pair.get("recordable")),
        "recorded": bool(pair.get("recorded")),
        "our_links": pair.get("our_links") or [],
    }


def build_markdown(entries, meta):
    lines = [
        "# 分类学变动对照表",
        "",
        "> 本表由 `_tools/build_taxonomy_crosswalk.py` 从 `_data/name_issues.json` 生成；"
        "不要手改，`name_issues.json` 更新后重跑即可。",
        "> 数据缓存日期：%s。这里只整理**已进入站内一致性核对**的 8 个种级条目；"
        "未列入的属级／种级变动仍须回原文核对。" % meta["cache_date"],
        "",
        "## 怎么用",
        "",
        "1. 写旧文献前先按旧名或现用名在本表查一行；没有命中就查 `_data/name_issues.json` 的 "
        "`issues`，仍没有就标「待核」，不要凭记忆改分类位置。",
        "2. 「旧名」指文献里可能遇到的组合；「本站现用」是当前页面接受的名字。"
        "两者不同时，正文必须带时间限定（「当时置于…」「本站现置于…」），不能把旧名直接当现行名。",
        "3. 表中「争议／未定」的条目不要写成学界共识；「可记录（待处理）」表示三大库一致、"
        "但站内尚未合并，写作时只陈述差异，不要擅自合并页面。",
        "4. 本表只解决**命名／组合对照**，不替代年代、模式产地、分布的原位核对。",
        "",
        "## 对照表",
        "",
        "| 本站现用名 | 文献中可能遇到的旧名 | 变动 | 旧属 → 现属 | 处理口径 | 状态 | 旧名链接 |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for entry in entries:
        site = entry["site"]
        authority = entry["authority"]
        site_label = "%s %s" % (site["latin"], ("（%s）" % site["zh"]) if site["zh"] else "")
        old_label = authority["name"] or authority["latin"]
        change = "%s / %s" % (entry["relation"], entry["direction"])
        genus = "%s → %s" % (entry["genus_from"] or "—", entry["genus_to"] or "—")
        links = source_links(authority["links"], entry["sources"])
        lines.append("| %s | %s | %s | %s | %s | %s | %s |" % (
            site_label, old_label, change, genus, entry["guidance"], entry["status"], links))
    lines += [
        "",
        "## 逐条备注",
        "",
    ]
    for entry in entries:
        site = entry["site"]
        authority = entry["authority"]
        lines.append("### %s ↔ %s" % (site["latin"], authority["latin"] or authority["name"]))
        lines.append("")
        lines.append("- 本站页面：`%s`%s" % (
            site["url"] or "—",
            "（%s）" % site["zh"] if site["zh"] else "",
        ))
        if entry["receiving"]["latin"] and entry["receiving"]["latin"] != site["latin"]:
            lines.append("- 外部库接收名：%s `%s`" % (
                entry["receiving"]["latin"], entry["receiving"]["url"] or "—"))
        lines.append("- 关系：%s；方向：%s；争议：%s" % (
            entry["relation"], entry["direction"], "是" if entry["disputed"] else "否"))
        lines.append("- 处理：%s" % entry["guidance"])
        lines.append("")
    lines += [
        "## 复核入口",
        "",
        "- `_data/name_issues.json`：完整 328 条一致性核对结果（含 `synonym_pairs`、"
        "`species_authority`、`issues`）。",
        "- `_data/taxonomy_crosswalk.json`：本表的机器可读版本，供扫描器/后续脚本使用。",
        "- `.sources/index.json`：每条判断对应的来源存档；正文用 `<!-- src:Sxxxx -->`。",
        "",
    ]
    return "\n".join(lines)


def main(argv=None):
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
        sys.stderr.reconfigure(encoding="utf-8")
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="只校验输出是否与 name_issues.json 同步，不写文件")
    args = parser.parse_args(argv)

    issues = load_json(NAME_ISSUES_PATH)
    pairs = issues.get("synonym_pairs") or []
    entries = [build_entry(pair) for pair in pairs]
    cache_dates = (issues.get("meta") or {}).get("cache_dates") or {}
    cache_date = (cache_dates.get("authority") or "")[:10] or "unknown"
    payload = {
        "_meta": {
            "title": "Taxonomy change crosswalk for the daily literature run",
            "source": "_data/name_issues.json",
            "generated_by": "_tools/build_taxonomy_crosswalk.py",
            "cache_date": cache_date,
            "count": len(entries),
            "note": ("Species-level synonym/combination pairs only. "
                     "The table is a guardrail, not a taxonomic decision."),
        },
        "entries": entries,
    }
    markdown = build_markdown(entries, payload["_meta"])

    if args.check:
        ok = True
        if not OUT_JSON.is_file() or load_json(OUT_JSON) != payload:
            print("不同步：%s" % OUT_JSON, file=sys.stderr)
            ok = False
        if not OUT_MD.is_file() or OUT_MD.read_text(encoding="utf-8") != markdown:
            print("不同步：%s" % OUT_MD, file=sys.stderr)
            ok = False
        if ok:
            print("分类学对照表已同步：%d 条" % len(entries))
        return 0 if ok else 1

    dump_json(OUT_JSON, payload)
    OUT_MD.parent.mkdir(parents=True, exist_ok=True)
    OUT_MD.write_text(markdown, encoding="utf-8")
    print("写入 %s（%d 条）" % (OUT_JSON, len(entries)))
    print("写入 %s" % OUT_MD)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
